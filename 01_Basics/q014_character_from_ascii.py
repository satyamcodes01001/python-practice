"""
Question 14: Character from ASCII

Problem Statement:
Take an ASCII value as input.
Print the corresponding character.

Example:
Input:
97

Output:
a
"""

# Code:

a = int(input())
print(chr(a))

# Concept Cleared:

# chr(97) = 'a' (ASCII/Unicode value to character)
# ord('a') = 97 (character to ASCII/Unicode value)

# ord() and chr() are opposite functions