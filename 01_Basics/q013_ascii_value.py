"""
Question 13: ASCII Value

Problem Statement:
Take a single character as input.
Print its ASCII value.

Example:
Input:
A

Output:
65
"""

# Code:

a=input()
# print(ascii(a)) "I used this.."
print(ord(a))


# Concept Cleared:

# ord('A') = 65 (ASCII/Unicode code point)
# ascii('A') = "'A'" (string representation)